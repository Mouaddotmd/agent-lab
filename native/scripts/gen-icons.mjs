// Copies the web app's icon artwork (const I in src/renderer/app.js) into Swift, so both draw the same paths.
import fs from 'node:fs';
const src = fs.readFileSync(new URL('../../src/renderer/app.js', import.meta.url), 'utf8');
const I = JSON.parse(src.match(/^const I = (\{.*\});$/m)[1]);
const out = ['// Generated by native/scripts/gen-icons.mjs from src/renderer/app.js. Do not edit.', 'enum IconData {', '    static let all: [String: [IconShape]] = ['];
for (const [name, svg] of Object.entries(I)) {
  const shapes = [];
  for (const m of svg.matchAll(/<(path|circle)\b([^>]*)\/?>/g)) {
    const a = Object.fromEntries([...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map((x) => [x[1], x[2]]));
    const sw = a['stroke-width'] || '1.5';
    if (m[1] === 'path') shapes.push(`.path(${JSON.stringify(a.d)}, stroke: ${sw}, join: ${a['stroke-linejoin'] === 'round' ? '.round' : '.miter'}, cap: ${a['stroke-linecap'] === 'round' ? '.round' : '.butt'})`);
    else shapes.push(`.circle(cx: ${a.cx}, cy: ${a.cy}, r: ${a.r}, stroke: ${sw})`);
  }
  out.push(`        ${JSON.stringify(name)}: [${shapes.join(', ')}],`);
}
out.push('    ]', '}', '');
fs.writeFileSync(new URL('../Sources/IconData.swift', import.meta.url), out.join('\n'));
console.log(Object.keys(I).length, 'icons');
